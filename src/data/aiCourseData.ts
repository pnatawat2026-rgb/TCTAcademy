export function interpretAIReadiness(score: number): { level: string; label: string; description: string; color: string } {
  if (score >= 50) {
    return {
      level: 'AI Ready (ระดับพร้อมสูง)',
      label: 'พร้อมต่อยอดสู่การใช้งานขั้นสูงและเป็น AI Champion ในแผนก',
      description: 'ท่านมีความรู้พื้นฐานและทัศนคติที่ดีเยี่ยม พร้อมเป็นแกนนำถ่ายทอดและประยุกต์ใช้ AI ในหน่วยงาน',
      color: 'text-emerald-400 border-emerald-500/40 bg-emerald-950/40'
    };
  }
  if (score >= 35) {
    return {
      level: 'Developing (ระดับกำลังพัฒนา)',
      label: 'มีพื้นฐานดี ควรเข้าอบรมเชิงลึกและฝึกปฏิบัติเพิ่มเติม',
      description: 'ท่านมีความเข้าใจพื้นฐานที่ดี การเข้าเรียน 7 โมดูลนี้จะช่วยยกระดับทักษะการเขียน Prompt และ Data Privacy ได้อย่างชัดเจน',
      color: 'text-cyan-400 border-cyan-500/40 bg-cyan-950/40'
    };
  }
  if (score >= 20) {
    return {
      level: 'Emerging (ระดับเริ่มต้น)',
      label: 'ควรเริ่มจากพื้นฐาน AI for TCT ตั้งแต่บทที่ 1 อย่างเป็นขั้นเป็นตอน',
      description: 'เหมาะอย่างยิ่งสำหรับการเริ่มต้นเรียนรู้หลักสูตรนี้ ค่อยๆ ศึกษาและทดลองเล่นมินิเกมเพื่อสร้างความมั่นใจ',
      color: 'text-amber-400 border-amber-500/40 bg-amber-950/40'
    };
  }
  return {
    level: 'Needs Foundation (ระดับต้องเสริมพื้นฐาน)',
    label: 'แนะนำให้เข้าอบรมแบบมีพี่เลี้ยง (Coaching) ควบคู่กับระบบออนไลน์',
    description: 'ไม่ต้องกังวล หลักสูตรนี้ถูกออกแบบให้เข้าใจง่าย ไม่มีศัพท์เทคนิคซับซ้อน สามารถทบทวนซ้ำได้ไม่จำกัด',
    color: 'text-rose-400 border-rose-500/40 bg-rose-950/40'
  };
}

